-- APLICADA el 11-oct-2026 (migración fab_copia_a_pruebas). Clave creada en el vault de producción y copiada al vault de pruebas.
-- Entorno de pruebas (proyecto Supabase «fabrica-pruebas», 11-oct-2026).
-- Dos funciones de producción, protegidas con una clave del vault (fab_copia_token), para montar y refrescar el
-- proyecto de pruebas sin copiar nada a mano:
--   fab_esquema_ddl(token)  → el SQL completo de la estructura de la fábrica (tablas, reglas, funciones, disparadores),
--                              generado en el momento desde el catálogo: es exactamente lo que hay en producción.
--   fab_copia_pruebas(token) → copia ANONIMIZADA de pedidos y prendas (sin nombres, emails, teléfonos ni direcciones;
--                              los textos de personalización se sustituyen) + configuración, modelos y almacén.
-- El proyecto de pruebas las llama con pg_net y la clave publicable (rol anon); sin la clave no devuelven nada.
-- La clave se crea con: select vault.create_secret('<clave>', 'fab_copia_token');

create or replace function public.fab_esquema_ddl(p_token text)
returns text language plpgsql security definer set search_path to '' as $$
declare
  tab text; con text; idx text; rls text; pol text; fun text; trg text; pub text;
begin
  if p_token is null or p_token is distinct from public.read_secret('fab_copia_token') then raise exception 'no autorizado'; end if;
  with t as (select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
              where n.nspname = 'public' and c.relkind = 'r' and c.relname like 'fab\_%')
  select string_agg(ddl, E'\n' order by relname) into tab from (
    select t.relname, format(E'create table if not exists public.%I (\n  %s\n);', t.relname, string_agg(format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
      case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end,
      coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), ''), case when a.attnotnull then ' not null' else '' end), E',\n  ' order by a.attnum)) ddl
    from t join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum
    group by t.relname) x;
  select string_agg(format('alter table public.%I add constraint %I %s;', c.relname, k.conname, pg_get_constraintdef(k.oid)), E'\n'
           order by case k.contype when 'p' then 0 when 'u' then 1 when 'c' then 2 else 3 end, c.relname) into con
    from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relname like 'fab\_%';
  select string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n') into idx
    from pg_index i join pg_class c on c.oid = i.indrelid join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relname like 'fab\_%' and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid);
  select string_agg(format('alter table public.%I enable row level security;', c.relname), E'\n') into rls
    from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'r' and c.relname like 'fab\_%' and c.relrowsecurity;
  select string_agg(format('create policy %I on public.%I as %s for %s to %s%s%s;', policyname, tablename, permissive, cmd, array_to_string(roles, ', '),
           coalesce(' using (' || qual || ')', ''), coalesce(' with check (' || with_check || ')', '')), E'\n') into pol
    from pg_policies where schemaname = 'public' and tablename like 'fab\_%';
  select string_agg(pg_get_functiondef(p.oid) || E';\n' ||
           format('revoke all on function public.%I(%s) from public, anon, authenticated;', p.proname, pg_get_function_identity_arguments(p.oid)) ||
           case when has_function_privilege('authenticated', p.oid, 'execute') then format(E'\ngrant execute on function public.%I(%s) to authenticated;', p.proname, pg_get_function_identity_arguments(p.oid)) else '' end ||
           case when has_function_privilege('anon', p.oid, 'execute') then format(E'\ngrant execute on function public.%I(%s) to anon;', p.proname, pg_get_function_identity_arguments(p.oid)) else '' end,
           E'\n\n' order by case when p.proname in ('read_secret', 'fab_es_usuario', 'fab_autoasignar') then 0 else 1 end, p.proname) into fun
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and (p.proname like 'fab\_%' or p.proname = 'read_secret') and p.proname not in ('fab_esquema_ddl', 'fab_copia_pruebas');
  select string_agg(pg_get_triggerdef(tg.oid) || ';', E'\n') into trg
    from pg_trigger tg join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relname like 'fab\_%' and not tg.tgisinternal;
  select string_agg(format('alter publication supabase_realtime add table public.%I;', tablename), E'\n') into pub
    from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename like 'fab\_%';
  return concat_ws(E'\n\n',
    '-- Estructura de la fábrica generada desde producción el ' || now()::text,
    'create sequence if not exists public.fab_eventos_id_seq;',
    tab, con, idx, rls, fun, pol, trg, pub,
    'alter sequence public.fab_eventos_id_seq owned by public.fab_eventos.id;');
end $$;
revoke all on function public.fab_esquema_ddl(text) from public, authenticated;
grant execute on function public.fab_esquema_ddl(text) to anon;

create or replace function public.fab_copia_pruebas(p_token text)
returns jsonb language plpgsql security definer set search_path to '' as $$
begin
  if p_token is null or p_token is distinct from public.read_secret('fab_copia_token') then raise exception 'no autorizado'; end if;
  return jsonb_build_object(
    'pedidos', (select coalesce(jsonb_agg(x), '[]') from (
      select p.order_id, p.order_name, p.creado_shopify, p.importado_at, p.cancelado, p.enviado_fuera,
             'Cliente ' || right(p.order_name, 3) as cliente_nombre,
             case when p.direccion1 is null then null else 'Calle de prueba ' || right(p.order_name, 2) end as direccion1,
             p.ciudad, p.provincia, p.cp, p.pais, p.metodo_envio, p.tags,
             case when p.nota is null then null else 'Nota de prueba' end as nota, p.peso_kg
        from public.fab_pedidos p
       where p.estado <> 'producido' or p.estado_at > now() - interval '30 days') x),
    'lineas', (select coalesce(jsonb_agg(y), '[]') from (
      select l.line_id, l.order_id, l.titulo, l.variante, l.sku, l.cantidad, l.estado, l.sin_vinilo, l.stock, l.product_id, l.variant_id, l.imagen_url,
             coalesce((select jsonb_agg(jsonb_build_object('key', e->>'key', 'value', 'TXT' || right(l.line_id::text, 3))) from jsonb_array_elements(l.personalizacion) e), '[]'::jsonb) as personalizacion
        from public.fab_lineas l join public.fab_pedidos p on p.order_id = l.order_id
       where p.estado <> 'producido' or p.estado_at > now() - interval '30 days') y),
    'config', (select coalesce(jsonb_agg(c), '[]') from public.fab_config c),
    'modelos', (select coalesce(jsonb_agg(m), '[]') from public.fab_modelos m),
    'cortados', (select coalesce(jsonb_agg(k), '[]') from public.fab_cortados k),
    'usuarios', (select coalesce(jsonb_agg(u), '[]') from public.fab_usuarios u));
end $$;
revoke all on function public.fab_copia_pruebas(text) from public, authenticated;
grant execute on function public.fab_copia_pruebas(text) to anon;
